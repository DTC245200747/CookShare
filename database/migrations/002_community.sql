CREATE TABLE IF NOT EXISTS user_profiles (
 user_id INT UNSIGNED PRIMARY KEY,
 bio VARCHAR(1000) NOT NULL DEFAULT '',
 avatar_url VARCHAR(2048) NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS user_security (
 user_id INT UNSIGNED PRIMARY KEY,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 token_version INT UNSIGNED NOT NULL DEFAULT 0,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS recipe_moderation (
 recipe_id INT UNSIGNED PRIMARY KEY,
 status ENUM('published','hidden') NOT NULL DEFAULT 'published',
 FOREIGN KEY(recipe_id) REFERENCES recipes(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS favorites (
 user_id INT UNSIGNED NOT NULL,
 recipe_id INT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,recipe_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(recipe_id) REFERENCES recipes(id) ON DELETE CASCADE,
 INDEX idx_favorites_recipe(recipe_id)
);
CREATE TABLE IF NOT EXISTS ratings (
 user_id INT UNSIGNED NOT NULL,
 recipe_id INT UNSIGNED NOT NULL,
 score TINYINT UNSIGNED NOT NULL,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(user_id,recipe_id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(recipe_id) REFERENCES recipes(id) ON DELETE CASCADE,
 CHECK(score BETWEEN 1 AND 5),
 INDEX idx_ratings_recipe(recipe_id)
);
CREATE TABLE IF NOT EXISTS comments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id INT UNSIGNED NOT NULL,
 recipe_id INT UNSIGNED NOT NULL,
 content VARCHAR(2000) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(recipe_id) REFERENCES recipes(id) ON DELETE CASCADE,
 INDEX idx_comments_recipe_created(recipe_id,created_at)
);
